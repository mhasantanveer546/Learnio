document.addEventListener("DOMContentLoaded", () => {
    const badge = document.getElementById("notif-badge");
    const list = document.getElementById("notif-list");
    const markAllBtn = document.getElementById("notif-mark-all-read");
    const bellBtn = document.getElementById("notif-bell-btn");

    if (!badge || !list) return; // not logged in / not on a page with the dropdown

    async function refreshUnreadCount() {
        const response = await fetch("/notifications/unread-count");
        const data = await response.json();

        if (data.count > 0) {
            badge.textContent = data.count > 9 ? "9+" : data.count;
            badge.classList.remove("d-none");
        } else {
            badge.classList.add("d-none");
        }
    }

    async function loadNotifications() {
        const response = await fetch("/notifications/");
        const notifications = await response.json();

        if (notifications.length === 0) {
            list.innerHTML = `<li class="px-3 py-4 text-center text-muted small">No notifications yet.</li>`;
            return;
        }

        list.innerHTML = notifications.map((n) => `
            <li>
                <a href="${n.link || '#'}"
                   class="dropdown-item px-3 py-2 border-bottom small ${n.is_read ? 'text-muted' : 'fw-semibold'}"
                   data-notif-id="${n.id}">
                    ${escapeHtml(n.message)}
                    <div class="text-muted" style="font-size: 0.75rem;">${formatRelativeTime(n.created_at)}</div>
                </a>
            </li>
        `).join("");

        list.querySelectorAll("[data-notif-id]").forEach((item) => {
            item.addEventListener("click", () => markRead(item.dataset.notifId));
        });
    }

    async function markRead(notificationId) {
        await fetch(`/notifications/${notificationId}/read`, {
            method: "POST",
            headers: { "X-CSRFToken": document.querySelector('meta[name="csrf-token"]').content },
        });
        refreshUnreadCount();
    }

    async function markAllRead() {
        await fetch("/notifications/mark-all-read", {
            method: "POST",
            headers: { "X-CSRFToken": document.querySelector('meta[name="csrf-token"]').content },
        });
        refreshUnreadCount();
        loadNotifications();
    }

    function formatRelativeTime(isoString) {
        const diffMs = Date.now() - new Date(isoString).getTime();
        const diffHours = Math.floor(diffMs / (1000 * 60 * 60));
        if (diffHours < 1) return "Just now";
        if (diffHours < 24) return `${diffHours}h ago`;
        return `${Math.floor(diffHours / 24)}d ago`;
    }

    function escapeHtml(text) {
        const div = document.createElement("div");
        div.textContent = text;
        return div.innerHTML;
    }

    if (bellBtn) {
        bellBtn.addEventListener("click", loadNotifications);
    }
    if (markAllBtn) {
        markAllBtn.addEventListener("click", markAllRead);
    }

    refreshUnreadCount();
    // Re-check unread count periodically, in case a new notification
    // gets generated by a dashboard visit in another tab.
    setInterval(refreshUnreadCount, 60000);
});